//! Generation of the commented `config.toml` written by `st config init`.
//!
//! The document is produced *from a real [`Config`] value*, so it can never
//! describe a default the code does not have: the value of every key is
//! serialised from the struct, and a test asserts that the comment table below
//! covers exactly the keys the struct serialises.

use crate::error::ConfigError;
use crate::Config;

/// One documented key inside a section.
struct Key {
    /// The key name as it appears in TOML.
    name: &'static str,
    /// Comment lines emitted above the key (without the leading `# `).
    doc: &'static [&'static str],
    /// Rendered as a commented-out line when the key is absent from the
    /// serialised document (an unset `Option`).
    absent: Option<&'static str>,
}

/// One `[section]` of the generated document.
struct Section {
    /// Dotted path into the serialised document (`"window.padding"`).
    path: &'static str,
    /// Comment lines emitted above the `[section]` header.
    doc: &'static [&'static str],
    /// Keys in emission order. Ignored when `dynamic` is set.
    keys: &'static [Key],
    /// Emit every key found in the table instead of `keys` (for free-form maps).
    dynamic: bool,
    /// Extra literal lines (already comment-prefixed) emitted after the keys.
    trailer: &'static [&'static str],
}

const fn key(name: &'static str, doc: &'static [&'static str]) -> Key {
    Key {
        name,
        doc,
        absent: None,
    }
}

const fn opt_key(name: &'static str, doc: &'static [&'static str], absent: &'static str) -> Key {
    Key {
        name,
        doc,
        absent: Some(absent),
    }
}

const fn section(
    path: &'static str,
    doc: &'static [&'static str],
    keys: &'static [Key],
) -> Section {
    Section {
        path,
        doc,
        keys,
        dynamic: false,
        trailer: &[],
    }
}

