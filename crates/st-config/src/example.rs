/// Renders the fully commented document for `config`.
pub(crate) fn render(config: &Config) -> Result<String, ConfigError> {
    let doc = toml::Table::try_from(config)?;
    let mut out = String::with_capacity(4096);

    for line in HEADER {
        push_comment(&mut out, line);
    }

    for sec in SECTIONS {
        out.push('\n');
        for line in sec.doc {
            push_comment(&mut out, line);
        }
        out.push('[');
        out.push_str(sec.path);
        out.push_str("]\n");

        let table = lookup(&doc, sec.path);

        if sec.dynamic {
            if let Some(table) = table {
                for (name, value) in table {
                    out.push_str(&render_pair(name, value)?);
                }
            }
        } else {
            for k in sec.keys {
                let value = table.and_then(|t| t.get(k.name));
                match (value, k.absent) {
                    (Some(value), _) => {
                        push_key_doc(&mut out, k.doc);
                        out.push_str(&render_pair(k.name, value)?);
                    }
                    (None, Some(absent)) => {
                        push_key_doc(&mut out, k.doc);
                        out.push_str("# ");
                        out.push_str(absent);
                        out.push('\n');
                    }
                    (None, None) => {
                        return Err(ConfigError::Serialize(missing_key(sec.path, k.name)));
                    }
                }
            }
        }

        for line in sec.trailer {
            out.push_str(line);
            out.push('\n');
        }
    }

    Ok(out)
}

/// Builds the `toml::ser::Error` used when the comment table and the struct
/// have drifted apart. Only reachable through a programming mistake, which the
/// `covers_every_serialised_key` test catches first.
fn missing_key(section: &str, key: &str) -> toml::ser::Error {
    serde::ser::Error::custom(format!(
        "config example template lists `{section}.{key}`, which the schema does not serialise"
    ))
}

/// Emits a key's comment block. An empty line becomes a real blank line, which
/// separates groups of keys inside one section.
fn push_key_doc(out: &mut String, doc: &[&str]) {
    for line in doc {
        if line.is_empty() {
            out.push('\n');
        } else {
            push_comment(out, line);
        }
    }
}

fn push_comment(out: &mut String, line: &str) {
    if line.is_empty() {
        out.push_str("#\n");
    } else {
        out.push_str("# ");
        out.push_str(line);
        out.push('\n');
    }
}

/// Formats `name = value` by asking the TOML serialiser, so quoting and
/// escaping are never hand-rolled.
fn render_pair(name: &str, value: &toml::Value) -> Result<String, ConfigError> {
    let mut one = toml::Table::new();
    one.insert(name.to_owned(), value.clone());
    Ok(toml::to_string(&one)?)
}

/// Walks a dotted path into a table.
fn lookup<'a>(doc: &'a toml::Table, path: &str) -> Option<&'a toml::Table> {
    let mut current = doc;
    for part in path.split('.') {
        current = current.get(part)?.as_table()?;
    }
    Some(current)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    /// Collects the dotted path of every scalar in the document.
    fn leaf_paths(value: &toml::Value, prefix: &str, out: &mut BTreeSet<String>) {
        match value {
            toml::Value::Table(t) => {
                for (k, v) in t {
                    let path = if prefix.is_empty() {
                        k.clone()
                    } else {
                        format!("{prefix}.{k}")
                    };
                    leaf_paths(v, &path, out);
                }
            }
            _ => {
                out.insert(prefix.to_owned());
            }
        }
    }

    #[test]
    fn covers_every_serialised_key() {
        let doc = toml::Value::Table(toml::Table::try_from(Config::default()).unwrap());
        let mut actual = BTreeSet::new();
        leaf_paths(&doc, "", &mut actual);

        let mut templated = BTreeSet::new();
        for sec in SECTIONS {
            if sec.dynamic {
                continue;
            }
            for k in sec.keys {
                templated.insert(format!("{}.{}", sec.path, k.name));
            }
        }
        // Optional keys are absent from a default document but templated.
        let optional: BTreeSet<String> = SECTIONS
            .iter()
            .flat_map(|s| {
                s.keys
                    .iter()
                    .filter(|k| k.absent.is_some())
                    .map(move |k| format!("{}.{}", s.path, k.name))
            })
            .collect();

        assert_eq!(
            &templated - &optional,
            actual,
            "docs/config-example.toml template is out of sync with the schema"
        );
    }

    #[test]
    fn sections_are_unique_and_ordered_parents_first() {
        let mut seen: Vec<&str> = Vec::new();
        for sec in SECTIONS {
            assert!(!seen.contains(&sec.path), "duplicate section {}", sec.path);
            if let Some((parent, _)) = sec.path.rsplit_once('.') {
                assert!(
                    seen.contains(&parent),
                    "{} must come after [{parent}]",
                    sec.path
                );
            }
            seen.push(sec.path);
        }
    }
}
